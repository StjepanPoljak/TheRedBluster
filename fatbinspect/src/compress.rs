//! Fatbin entry payload compression (flags at entry +0x28).

use crate::util::err;
use std::io;

#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub enum Compression {
    /// `0x1000`
    Zlib,
    /// `0x2000`: LZ4 raw block (CUDA 11–12 default).
    Lz4,
    /// `0x4000`: "LZ4Compression2".
    Lz4v2,
    /// `0x8000`: CUDA 12.8+/13.
    Zstd
}

impl Compression {
    pub fn from_flags(flags: u64) -> Option<Compression> {
        if flags & 0x1000 != 0 {
            Some(Compression::Zlib)
        } else if flags & 0x2000 != 0 {
            Some(Compression::Lz4)
        } else if flags & 0x4000 != 0 {
            Some(Compression::Lz4v2)
        } else if flags & 0x8000 != 0 {
            Some(Compression::Zstd)
        } else {
            None
        }
    }

    pub fn name(self) -> &'static str {
        match self {
            Compression::Zlib => "zlib",
            Compression::Lz4 => "LZ4",
            Compression::Lz4v2 => "LZ4 (v2)",
            Compression::Zstd => "zstd"
        }
    }
}

/// Decompress a stored payload to exactly `uncompressed_size` bytes.
pub fn decompress(c: Compression, data: &[u8], uncompressed_size: usize) -> io::Result<Vec<u8>> {
    let out = match c {
        Compression::Lz4 => {
            // A byte of LZ4 input expands to at most ~255 bytes; reject sizes
            // that would only make us allocate a huge buffer.
            if uncompressed_size > data.len().saturating_mul(255).saturating_add(64) {
                return err(format!("LZ4 payload of {} bytes can't decompress to {} bytes",
                    data.len(), uncompressed_size));
            }
            lz4_flex::block::decompress(data, uncompressed_size)
                .or_else(|e| err(format!("LZ4 decompression failed: {}", e)))?
        },
        Compression::Zstd => decompress_zstd(data, uncompressed_size)?,
        _ => return err(format!("{} decompression is not supported yet", c.name()))
    };
    if out.len() != uncompressed_size {
        return err(format!("{} payload decompressed to {} bytes, expected {}",
            c.name(), out.len(), uncompressed_size));
    }
    Ok(out)
}

#[cfg(feature = "zstd")]
fn decompress_zstd(data: &[u8], uncompressed_size: usize) -> io::Result<Vec<u8>> {
    use std::io::Read;
    let mut out = Vec::new();
    // Read at most one byte more than expected, so the length check catches it.
    ruzstd::decoding::StreamingDecoder::new(data)
        .or_else(|e| err(format!("zstd decompression failed: {}", e)))?
        .take(uncompressed_size as u64 + 1)
        .read_to_end(&mut out)
        .or_else(|e| err(format!("zstd decompression failed: {}", e)))?;
    Ok(out)
}

#[cfg(not(feature = "zstd"))]
fn decompress_zstd(_data: &[u8], _uncompressed_size: usize) -> io::Result<Vec<u8>> {
    err("zstd decompression needs the `zstd` cargo feature")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lz4_roundtrip() {
        let input = b"\x7fELF repeated repeated repeated repeated payload".repeat(8);
        let packed = lz4_flex::block::compress(&input);
        assert_eq!(decompress(Compression::Lz4, &packed, input.len()).unwrap(), input);
        assert!(decompress(Compression::Lz4, &packed, input.len() + 1).is_err());
        assert!(decompress(Compression::Lz4, &packed[..packed.len() / 2], input.len()).is_err());
        assert!(decompress(Compression::Lz4, &packed, 1 << 40).is_err());
    }

    /// A frame from `zstd -19` (not from a real fatbin: that needs CUDA 12.8+).
    #[cfg(feature = "zstd")]
    #[test]
    fn zstd_frame() {
        let frame = [
            0x28, 0xb5, 0x2f, 0xfd, 0x24, 0x43, 0x19, 0x02, 0x00, 0x2f, 0x2f, 0x0a, 0x2f, 0x2f, 0x20, 0x47,
            0x65, 0x6e, 0x65, 0x72, 0x61, 0x74, 0x65, 0x64, 0x20, 0x62, 0x79, 0x20, 0x4e, 0x56, 0x49, 0x44,
            0x49, 0x41, 0x20, 0x4e, 0x56, 0x56, 0x4d, 0x20, 0x43, 0x6f, 0x6d, 0x70, 0x69, 0x6c, 0x65, 0x72,
            0x0a, 0x2e, 0x76, 0x65, 0x72, 0x73, 0x69, 0x6f, 0x6e, 0x20, 0x38, 0x2e, 0x34, 0x0a, 0x2e, 0x74,
            0x61, 0x72, 0x67, 0x65, 0x74, 0x20, 0x73, 0x6d, 0x5f, 0x35, 0x30, 0x0a, 0xac, 0xaa, 0xef, 0x15
        ];
        let text = b"//\n// Generated by NVIDIA NVVM Compiler\n.version 8.4\n.target sm_50\n";
        assert_eq!(decompress(Compression::Zstd, &frame, text.len()).unwrap(), text);
        assert!(decompress(Compression::Zstd, &frame[..frame.len() - 4], text.len()).is_err());
        assert!(decompress(Compression::Zstd, &frame, text.len() - 1).is_err());
    }

    #[cfg(not(feature = "zstd"))]
    #[test]
    fn zstd_needs_feature() {
        assert!(decompress(Compression::Zstd, &[], 0).is_err());
    }
}
